  function captureSpanish() {
    ui.es = {};
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var k = el.getAttribute("data-i18n");
      if (!(k in ui.es)) ui.es[k] = el.innerHTML.trim();
    });
    document.querySelectorAll("[data-i18n-attr]").forEach(function (el) {
      el.getAttribute("data-i18n-attr").split(";").forEach(function (pair) {
        var p = pair.split(":"), attr = p[0], k = p[1];
        if (attr && k && !(k in ui.es)) ui.es[k] = el.getAttribute(attr) || "";
      });
    });
  }

  function t(key, lang) {
    lang = lang || current;
    var d = ui[lang] || {};
    return key in d ? d[key] : (ui.es[key] || "");
  }

  function apply(lang) {
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var v = t(el.getAttribute("data-i18n"), lang);
      if (v && el.innerHTML !== v) el.innerHTML = v;
    });
    document.querySelectorAll("[data-i18n-attr]").forEach(function (el) {
      el.getAttribute("data-i18n-attr").split(";").forEach(function (pair) {
        var p = pair.split(":");
        if (p[0] && p[1]) el.setAttribute(p[0], t(p[1], lang));
      });
    });
    document.documentElement.lang = lang;
    var pageKey = window.__TARA_PAGE_TITLE__;
    document.title = (pageKey && pageTitles[pageKey] && pageTitles[pageKey][lang]) || dynamic[lang].htmlTitle;
    document.querySelectorAll("[data-lang]").forEach(function (b) {
      var on = b.getAttribute("data-lang") === lang;
      if (b.closest(".lang")) b.setAttribute("aria-pressed", on ? "true" : "false");
      else b.setAttribute("aria-current", on ? "true" : "false");
    });
  }

  function setLang(lang, animate) {
    if (SUPPORTED.indexOf(lang) === -1) lang = "es";
    var changed = lang !== current;
    current = lang;
    try { localStorage.setItem(KEY, lang); } catch (e) {}
    if (animate && changed) {
      document.body.classList.add("i18n-fading");
      setTimeout(function () {
        apply(lang);
        listeners.forEach(function (fn) { try { fn(lang); } catch (e) {} });
        document.body.classList.remove("i18n-fading");
      }, 220);
    } else {
      apply(lang);
      listeners.forEach(function (fn) { try { fn(lang); } catch (e) {} });
    }
  }

